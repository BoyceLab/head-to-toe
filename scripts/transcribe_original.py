"""One-time transcription of the original Health Survey from the 2018 supplement (a .docx file).

Kept for provenance; the supplement itself is not part of this repository.
Usage: python scripts/transcribe_original.py supplement.docx content/original/health-survey-2018.yaml
Needs python-docx in addition to PyYAML, and the HPO files from scripts/fetch_hpo.py.
"""
import sys, re, pathlib, docx, yaml
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import hpo
from docx.oxml.ns import qn
from docx.table import Table
from docx.text.paragraph import Paragraph
d=docx.Document(sys.argv[1])
ROOT=pathlib.Path(__file__).resolve().parent.parent
TAG=yaml.safe_load((ROOT/'config.yaml').read_text())['hpo_release']
T=hpo.Ontology(ROOT/'.cache'/'hpo'/TAG/'hp.obo').terms
KEYS=['birth','growth','hormones','cancer','head','eyes','ears','brain','behavior','skin','bones','muscles','heart','breathing','digestion','kidneys','immune','blood','mouth']
blocks=[]
for ch in d.element.body.iterchildren():
    if ch.tag==qn('w:p'):
        p=Paragraph(ch,d); t=p.text.strip()
        if t: blocks.append(('p',p.style.name,t))
    elif ch.tag==qn('w:tbl'):
        tb=Table(ch,d); rows=[[c.text.strip() for c in r.cells] for r in tb.rows]
        blocks.append(('t',rows))
def clean(s): return re.sub(r'\s+',' ',s).strip()
out={'title':'GenomeConnect Health Survey','source':'Supplementary information to Savatt et al., Human Mutation 2018 (NIHMS987694)','note':'Transcribed from the supplement as printed, including its typos and term labels. Do not edit this file to fix errors; record fixes in crosswalk.yaml.','intro':[],'screen':[],'detail':[],'end':[]}
i=0; mode='intro'; cur=None; sec=None
screen_i=0
def opts_after(j):
    o=[]
    while j<len(blocks) and blocks[j][0]=='p' and blocks[j][1] in ('Body Text','List Paragraph') and not blocks[j][2].startswith('Examples') and not blocks[j][2].startswith('Please note') and not blocks[j][2].startswith('**') and not blocks[j][2].startswith('Have you had issues with your ORAL'):
        o.append(blocks[j][2]); j+=1
    return o,j
while i<len(blocks):
    b=blocks[i]
    if b[0]=='p':
        sty,t=b[1],b[2]
        m=re.match(r'(.+?)\s*\(only displayed if answered .Yes. to question (\d+) above\)',t)
        if m:
            mode='detail'; sec={'key':KEYS[len(out['detail'])],'heading':clean(m.group(1)),'shown_when':'Yes to question '+m.group(2),'questions':[],'notes':[],'rows':[],'time_columns':[]}
            out['detail'].append(sec); i+=1; continue
        if t=='Reference': mode='end'; i+=1; continue
        if mode=='intro' and t=='Health & Development': mode='screen'; i+=1; continue
        if mode=='intro':
            if sty.startswith('Heading 1') and t!='GenomeConnect - Health Survey': out['intro'].append({'section':t,'questions':[]}); i+=1; continue
            if sty.startswith('Heading 2'):
                if not out['intro']: out['intro'].append({'section':'About you','questions':[]})
                q={'question':t}; j=i+1; ex=[]
                while j<len(blocks) and blocks[j][0]=='p' and (blocks[j][2].startswith('Examples') or blocks[j][2].startswith('**')): ex.append(blocks[j][2]); j+=1
                if ex: q['help']=' '.join(ex)
                o,j=opts_after(j); q['options']=o; out['intro'][-1]['questions'].append(q); i=j; continue
        if mode=='screen':
            if t.startswith('Have you') or t.startswith('Have you been told'):
                q={'key':KEYS[screen_i],'number':screen_i+1,'question':t}; screen_i+=1; j=i+1; ex=[]
                while j<len(blocks) and blocks[j][0]=='p' and (blocks[j][2].startswith('Examples') or blocks[j][2].startswith('Please note')): ex.append(blocks[j][2]); j+=1
                if ex: q['examples']=' '.join(ex)
                o,j=opts_after(j); q['options']=o; out['screen'].append(q); i=j; continue
            if t.startswith('The following sections'): out['screen_note']=t
            i+=1; continue
        if mode=='detail':
            if t in ('Answers','Eyes/Vision'): i+=1; continue
            if sty.startswith('Heading 2') or sty=='Normal':
                if t.startswith('Sometimes babies'):
                    q={'question':t}; j=i+1; ex=[]
                    while j<len(blocks) and blocks[j][0]=='p' and blocks[j][2].startswith('If you were born'): ex.append(blocks[j][2]); j+=1
                    if ex: q['help']=' '.join(ex)
                    o,j=opts_after(j); q['options']=o; sec['questions'].append(q); i=j; continue
                sec['questions'].append({'question':t}); i+=1; continue
            sec['notes'].append(t); i+=1; continue
        if mode=='end':
            if t.startswith('Who referred') or t.startswith('Are you already') or t.startswith('To which group') or t.startswith('Are there additional'):
                q={'question':t}; j=i+1; o=[]
                while j<len(blocks) and blocks[j][0]=='p' and blocks[j][1] in ('Body Text','List Paragraph'): o.append(blocks[j][2]); j+=1
                if o: q['options']=o
                out['end'].append(q); i=j; continue
            i+=1; continue
        i+=1; continue
    else:
        rows=b[1]
        if sec is None: i+=1; continue
        start=1 if rows[0][0]=='Answers' else 0
        if start==1: sec['time_columns']=[clean(c.split('\n')[0]) for c in rows[0][2:]]
        if len(rows)>1 and len(rows[1])>2: sec['time_options']=[clean(x) for x in rows[1][2].split('\n')[1:] if x.strip() and not x.startswith('Repeated')]
        for r in rows[start:]:
            raw=r[0].strip(); hp=clean(r[1]) if len(r)>1 else ''
            if not raw: continue
            if '\n' in raw: lab,_,desc=raw.partition('\n'); lab=clean(lab); desc=clean(desc)
            else:
                c=clean(raw); m2=re.match(r'^(.+?)(?:\s[-–]\s?|[-–]\s)(.+)$',c) or re.match(r'^(.*?(?:issue|legs|shoulders|function|structure|muscles))\s+((?:Issues|Torticollis|Weakness).*)$',c)
                lab,desc=(m2.group(1),m2.group(2)) if m2 else (c,'')
            m=re.search(r'HP:\s?(\d{7})',hp) or re.search(r'\b(\d{7})\b',hp)
            row={'answer':lab.strip(),'description':desc.strip() or None,'hpo_as_printed':hp or None,'hpo_id':('HP:'+m.group(1)) if m else None}
            if row['hpo_id']:
                t=T.get(row['hpo_id']); row['current_label']=(t['name']+(' (obsolete)' if t['obs'] else '')) if t else 'not in current release'
            sec['rows'].append({k:v for k,v in row.items() if v is not None})
        i+=1
yaml.safe_dump(out, open(sys.argv[2],'w'), sort_keys=False, allow_unicode=True, width=1000)
print('screen',len(out['screen']),'detail',len(out['detail']),'rows',sum(len(s['rows']) for s in out['detail']),'intro',[ (s['section'],len(s['questions'])) for s in out['intro']],'end',len(out['end']))
for s in out['detail']: print(s['key'], s['heading'], len(s['rows']), s['shown_when'], s.get('time_columns'))
